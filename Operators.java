public class Operators{
        public static void main(String[] args)
        {
         int a=10,b=5;
         System.out.println("a+b ="+(a+b));
         // relational Operator
         System.out.println("a > b ? " + (a > b)); 
         // Logical Operator
         boolean x=true,y=false;
         System.out.println("x && y = " + (x&&y)); 
         // Assignment Operator
         System.out.println("a after a+5 =" + (a += 5));
         // Ternary Operator
         System.out.println("a max b = " + (a > b ?a:b)); 
         
        }
      }
