public class JavaTypes {
   public static void main(String args[]) {

      byte b1 = 2;
      byte b2 = 4;
      byte byteResult = (byte) (b1 + b2);
      System.out.println(byteResult);

      int value1 = 2;
      int value2 = 4;
      int intResult = value1 + value2;
      System.out.println(intResult);
   }
}